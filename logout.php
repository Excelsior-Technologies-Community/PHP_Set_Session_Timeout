<?php

require_once __DIR__ . '/config/db.php';
require_once __DIR__ . '/config/auth.php';


/*
|--------------------------------------------------------------------------
| Get Current User Before Destroying Session
|--------------------------------------------------------------------------
*/

$userId = isset($_SESSION['user_id'])
    ? (int) $_SESSION['user_id']
    : null;


/*
|--------------------------------------------------------------------------
| Log Manual Logout
|--------------------------------------------------------------------------
*/

if ($userId !== null) {

    logSessionEvent(
        $pdo,
        $userId,
        'logout'
    );
}


/*
|--------------------------------------------------------------------------
| Clear Remember Me
|--------------------------------------------------------------------------
*/

clearRememberCookie($pdo);


/*
|--------------------------------------------------------------------------
| Clear Session
|--------------------------------------------------------------------------
*/

$_SESSION = [];


/*
|--------------------------------------------------------------------------
| Remove Session Cookie
|--------------------------------------------------------------------------
*/

if (ini_get('session.use_cookies')) {

    $params = session_get_cookie_params();

    setcookie(
        session_name(),
        '',
        time() - 42000,
        $params['path'],
        $params['domain'],
        $params['secure'],
        $params['httponly']
    );
}


/*
|--------------------------------------------------------------------------
| Destroy Session
|--------------------------------------------------------------------------
*/

session_destroy();


/*
|--------------------------------------------------------------------------
| Redirect
|--------------------------------------------------------------------------
*/

if (isset($_GET['expired'])) {

    header(
        "Location: index.php?expired=1"
    );

} else {

    header(
        "Location: index.php?logout=1"
    );
}

exit();